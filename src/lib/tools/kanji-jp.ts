export const TW_TO_JP: Map<string, string> = (() => {
  const chars = [...PAIRS];
  const m = new Map<string, string>();
  for (let i = 0; i + 1 < chars.length; i += 2) if (chars[i] !== chars[i + 1]) m.set(chars[i], chars[i + 1]);
  return m;
})();

/** 逐字轉換；回傳每個字＋有沒有換 */
export function toJapaneseKanji(text: string): { ch: string; jp: string; changed: boolean }[] {
  return [...text].map((ch) => {
    const jp = TW_TO_JP.get(ch);
    return { ch, jp: jp ?? ch, changed: jp !== undefined };
  });
}
